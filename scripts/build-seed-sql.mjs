// Builds supabase/seed.sql from the example data in src/data/seed.js (tutors, sub-topics, reviews, groups),
// so the live database shows the same example tutors as the demo. Run: npm run seed-sql
// Everything it adds is marked: tutors.is_example = true, and review/seat authors are placeholder accounts
// with @seed.naflaasimon.invalid emails (no password, nobody can sign in with them).
// supabase/seed.sql is safe to run again: it removes the previous examples first.
// supabase/remove-examples.sql deletes all of them before the real launch.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { SEED_TUTORS, buildSeedReviews, buildSeedGroups } from '../src/data/seed.js';

const uuid = (key) => {
  const h = createHash('sha1').update('naflaasimon-seed:' + key).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) => (v === null || v === undefined || v === '' ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a && a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const DOMAIN = 'seed.naflaasimon.invalid';

const reviews = buildSeedReviews();
const { groups, seats } = buildSeedGroups();

// One placeholder account per review slot: a tutor's n-th review always comes from account n (reviews are unique per tutor and user).
const perTutor = {};
const reviewRows = reviews.map((r) => {
  const n = (perTutor[r.tutorId] = (perTutor[r.tutorId] || 0) + 1);
  return { ...r, user: n };
});
const seatRows = seats.map((s, i) => ({ ...s, user: 100 + i }));
const users = new Map();
reviewRows.forEach((r) => users.set(r.user, r.userName));
seatRows.forEach((s) => users.set(s.user, s.name));

const out = [];
out.push(`-- נפל האסימון: example tutors for the live site. Generated by scripts/build-seed-sql.mjs from src/data/seed.js; edit there.
-- Safe to run again. To delete every example before launch, run supabase/remove-examples.sql.
alter table public.tutors add column if not exists is_example boolean not null default false;

begin;
delete from public.tutors where is_example;
delete from auth.users where email like '%@${DOMAIN}';
select set_config('app.bypass', 'on', true);
`);

out.push('insert into auth.users (id, instance_id, aud, role, email, raw_user_meta_data, raw_app_meta_data, created_at, updated_at) values');
out.push([...users].map(([n, name]) =>
  `  (${q(uuid('user:' + n))}, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', ${q(`seed-${n}@${DOMAIN}`)}, ${q(JSON.stringify({ name }))}::jsonb, '{"provider":"seed"}'::jsonb, now(), now())`,
).join(',\n') + ';\n');

out.push('insert into public.tutors (id, name, photo, headline, about, subjects, levels, topics, availability, city, area, lat, lng, teaches_online, teaches_frontal, price_online, price_frontal, experience_years, verified, contact_count, created_at, is_example) values');
out.push(SEED_TUTORS.map((t) => `  (${[
  q(uuid('tutor:' + t.id)), q(t.name), q(t.photo), q(t.headline), q(t.about), arr(t.subjects), arr(t.levels), arr(t.topics), arr(t.availability),
  q(t.city), q(t.area), q(t.lat), q(t.lng), q(!!t.teachesOnline), q(!!t.teachesFrontal),
  q(t.teachesOnline ? t.priceOnline : null), q(t.teachesFrontal ? t.priceFrontal : null), q(t.experienceYears), q(t.verified !== false), q(t.contactCount || 0), q(t.createdAt), 'true',
].join(', ')})`).join(',\n') + ';\n');

out.push('insert into public.tutor_contacts (tutor_id, phone) values');
out.push(SEED_TUTORS.map((t) => `  (${q(uuid('tutor:' + t.id))}, ${q(t.phone)})`).join(',\n') + ';\n');

out.push('insert into public.reviews (tutor_id, user_id, user_name, rating, text, created_at) values');
out.push(reviewRows.map((r) => `  (${q(uuid('tutor:' + r.tutorId))}, ${q(uuid('user:' + r.user))}, ${q(r.userName)}, ${r.rating}, ${q(r.text)}, ${q(r.createdAt)})`).join(',\n') + ';\n');

out.push('insert into public.groups (id, tutor_id, title, subject, level, description, start_date, time, sessions, mode, city, location, price_per_person, max_seats, join_mode, created_at) values');
out.push(groups.map((g) => `  (${[
  q(uuid('group:' + g.id)), q(uuid('tutor:' + g.tutorId)), q(g.title), q(g.subject), q(g.level), q(g.description), q(g.startDate), q(g.time), g.sessions,
  q(g.mode), q(g.city), q(g.location), g.pricePerPerson, g.maxSeats, q(g.joinMode || 'open'), q(g.createdAt),
].join(', ')})`).join(',\n') + ';\n');

out.push('insert into public.group_seats (group_id, user_id, name, phone, note, status, created_at) values');
out.push(seatRows.map((s) => `  (${q(uuid('group:' + s.groupId))}, ${q(uuid('user:' + s.user))}, ${q(s.name)}, ${q(s.phone)}, ${q(s.note)}, ${q(s.status || 'approved')}, ${q(s.createdAt)})`).join(',\n') + ';\n');

out.push(`select set_config('app.bypass', 'off', true);
commit;
`);

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
writeFileSync(new URL('../supabase/remove-examples.sql', import.meta.url), `-- נפל האסימון: removes every example tutor, review, group and placeholder account added by supabase/seed.sql.
-- Run before the real launch. Real tutors and users are not touched.
begin;
delete from public.tutors where is_example;
delete from auth.users where email like '%@${DOMAIN}';
commit;
`);
console.log(`seed.sql: ${SEED_TUTORS.length} tutors, ${reviewRows.length} reviews, ${groups.length} groups, ${seatRows.length} seats, ${users.size} placeholder accounts`);
